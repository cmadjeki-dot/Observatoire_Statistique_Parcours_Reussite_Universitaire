if (.Platform$OS.type == "windows") Sys.setlocale("LC_CTYPE", ".UTF-8")
shiny_app_dir <- project_path("dashboards/shiny")
shiny_helpers <- new.env(parent = globalenv())
source(file.path(shiny_app_dir, "helpers.R"), local = shiny_helpers, encoding = "UTF-8")

testthat::test_that("les cartes Shiny utilisent les comptes proteges et les bons denominateurs", {
  data <- shiny_helpers$load_dashboard_data(project_path())
  snap <- shiny_helpers$dashboard_snapshot(data, "2025-2026", "all")
  testthat::expect_equal(snap$school$inscrits, 10222)
  testthat::expect_equal(snap$success, 7478 / 10222)
  testthat::expect_equal(snap$satisfaction, 2942 / 4120)
  testthat::expect_equal(snap$participation, 4967 / 9805)
  testthat::expect_equal(snap$evolution, (10222 - 8026) / 8026)
  testthat::expect_true(snap$censored)
  testthat::expect_true(is.na(snap$employment_rate))
  testthat::expect_equal(shiny_helpers$dashboard_snapshot(data, "2025-2026", "F01")$school$inscrits, 2752)
  previous <- shiny_helpers$dashboard_snapshot(data, "2024-2025", "all")
  testthat::expect_equal(previous$employment$state, "masked")
  testthat::expect_true(is.na(previous$employment_rate))
  testthat::expect_equal(shiny_helpers$dashboard_rate(previous$school, "passages", "eligibles_passage"), 4067 / 6168)
})

testthat::test_that("les masques, les absences et les denominateurs nuls ne deviennent pas des zeros", {
  tiny <- data.frame(annee = "A", formation_id = c("F1", "F2"), masque = c(TRUE, FALSE), n = c(NA, 99), d = c(NA, 100))
  agg <- shiny_helpers$dashboard_aggregate(tiny, "A")
  testthat::expect_equal(agg$state, "masked")
  testthat::expect_null(agg$n)
  testthat::expect_true(is.na(shiny_helpers$dashboard_rate(agg, "n", "d")))
  testthat::expect_true(is.na(shiny_helpers$dashboard_rate(list(state = "ok", n = 0, d = 0), "n", "d")))
  testthat::expect_equal(shiny_helpers$dashboard_aggregate(tiny, "B")$state, "absent")
})

testthat::test_that("les entrees Shiny pilotent vraiment les sorties reactives et le graphique", {
  env <- new.env(parent = globalenv())
  old <- getwd(); on.exit(setwd(old), add = TRUE)
  setwd(shiny_app_dir)
  source("app.R", local = env, encoding = "UTF-8")
  shiny::testServer(env$server, {
    session$setInputs(year = "2025-2026", formation = "all", metric = "success", view = "overview")
    testthat::expect_equal(snapshot()$school$inscrits, 10222)
    testthat::expect_match(output$kpis$html, "73,2")
    testthat::expect_match(output$kpis$html, "71,4")
    testthat::expect_match(output$kpis$html, "Non observable")
    testthat::expect_equal(nrow(series()), 3L)
    testthat::expect_true(is.list(output$evolution_plot))
    session$setInputs(formation = "F01")
    testthat::expect_equal(snapshot()$school$inscrits, 2752)
    testthat::expect_equal(formation_label(), "Licence Alpha")
    session$setInputs(year = "2024-2025", formation = "all", view = "journeys")
    testthat::expect_match(output$kpis$html, "Masqué")
    testthat::expect_match(output$journey_kpis$html, "65,9")
    session$setInputs(metric = "enrolment")
    testthat::expect_equal(series()$valeur, c(5969, 8026, 10222))
    testthat::expect_match(output$chart_title, "effectifs")
    session$setInputs(metric = "satisfaction")
    testthat::expect_equal(tail(series()$valeur, 1), 2942 / 4120, ignore_attr = TRUE)
    session$setInputs(year = "2023-2024")
    testthat::expect_true(is.na(snapshot()$evolution))
  })
})
